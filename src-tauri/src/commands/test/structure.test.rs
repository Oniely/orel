#[test]
fn render_pg_create_table_includes_columns_and_constraints() {
    let ddl = render_pg_create_table(
        "items",
        vec![
            PgColumnDdl {
                name: "id".to_string(),
                data_type: "integer".to_string(),
                not_null: true,
                default_expr: Some("nextval('items_id_seq'::regclass)".to_string()),
                identity: String::new(),
                serial_type: None,
            },
            PgColumnDdl {
                name: "name".to_string(),
                data_type: "text".to_string(),
                not_null: true,
                default_expr: Some("'untitled'::text".to_string()),
                identity: String::new(),
                serial_type: None,
            },
        ],
        vec![
            PgConstraintDdl {
                name: "items_pkey".to_string(),
                definition: "PRIMARY KEY (id)".to_string(),
            },
            PgConstraintDdl {
                name: "items_name_key".to_string(),
                definition: "UNIQUE (name)".to_string(),
            },
            PgConstraintDdl {
                name: "items_name_check".to_string(),
                definition: "CHECK (name <> ''::text)".to_string(),
            },
        ],
    );

    assert!(ddl.contains("CREATE TABLE \"items\""));
    assert!(ddl.contains("\"id\" integer DEFAULT nextval('items_id_seq'::regclass) NOT NULL"));
    assert!(ddl.contains("\"name\" text DEFAULT 'untitled'::text NOT NULL"));
    assert!(ddl.contains("CONSTRAINT \"items_pkey\" PRIMARY KEY (id)"));
    assert!(ddl.contains("CONSTRAINT \"items_name_key\" UNIQUE (name)"));
    assert!(ddl.contains("CONSTRAINT \"items_name_check\" CHECK (name <> ''::text)"));
}

