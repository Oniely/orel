// PostgreSQL: DDL rendering, structure introspection, and ALTER TABLE generation.

use super::*;
use crate::commands::sql_util::{normalize_pg_type, pg_quote};

pub(super) struct PgColumnDdl {
    pub(super) name: String,
    pub(super) data_type: String,
    pub(super) not_null: bool,
    pub(super) default_expr: Option<String>,
    pub(super) identity: String,
    pub(super) serial_type: Option<String>,
}


pub(super) struct PgConstraintDdl {
    pub(super) name: String,
    pub(super) definition: String,
}


pub(super) fn render_pg_create_table(
    table: &str,
    columns: Vec<PgColumnDdl>,
    constraints: Vec<PgConstraintDdl>,
) -> String {
    let mut lines: Vec<String> = columns
        .into_iter()
        .map(|column| {
            let data_type = column.serial_type.as_deref().unwrap_or(&column.data_type);
            let mut line = format!("  {} {}", pg_quote(&column.name), data_type);

            match column.identity.as_str() {
                "a" => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
                "d" => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
                _ => {
                    if column.serial_type.is_none() {
                        if let Some(default_expr) = column.default_expr {
                            line.push_str(" DEFAULT ");
                            line.push_str(&default_expr);
                        }
                    }
                }
            }

            if column.not_null && column.serial_type.is_none() {
                line.push_str(" NOT NULL");
            }

            line
        })
        .collect();

    lines.extend(constraints.into_iter().map(|constraint| {
        format!(
            "  CONSTRAINT {} {}",
            pg_quote(&constraint.name),
            constraint.definition
        )
    }));

    format!(
        "CREATE TABLE {} (\n{}\n);",
        pg_quote(table),
        lines.join(",\n")
    )
}


pub(super) async fn fetch_postgres_ddl(pool: sqlx::PgPool, table: &str) -> Result<TableDdl, String> {
    let relkind = sqlx::query_scalar::<_, String>(
        "SELECT c.relkind::text \
         FROM pg_catalog.pg_class c \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         WHERE c.relname = $1 AND n.nspname = 'public'",
    )
    .bind(table)
    .fetch_optional(&pool)
    .await
    .map_err(|e| e.to_string())?
    .ok_or_else(|| format!("Table not found: {table}"))?;

    if relkind != "r" && relkind != "p" {
        return Err("DDL is only available for tables".to_string());
    }

    let column_rows =
        sqlx::query_as::<_, (String, String, bool, Option<String>, String, Option<String>)>(
            "SELECT \
            a.attname, \
            pg_catalog.format_type(a.atttypid, a.atttypmod), \
            a.attnotnull, \
            pg_catalog.pg_get_expr(ad.adbin, ad.adrelid), \
            a.attidentity::text, \
            CASE \
                WHEN serial_seq.oid IS NULL THEN NULL \
                WHEN a.atttypid = 'pg_catalog.int2'::regtype THEN 'smallserial'::text \
                WHEN a.atttypid = 'pg_catalog.int4'::regtype THEN 'serial'::text \
                WHEN a.atttypid = 'pg_catalog.int8'::regtype THEN 'bigserial'::text \
                ELSE NULL \
            END \
         FROM pg_catalog.pg_attribute a \
         JOIN pg_catalog.pg_class c ON c.oid = a.attrelid \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         LEFT JOIN pg_catalog.pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum \
         LEFT JOIN LATERAL ( \
            SELECT seq.oid \
            FROM pg_catalog.pg_depend dep \
            JOIN pg_catalog.pg_class seq ON seq.oid = dep.objid AND seq.relkind = 'S' \
            WHERE dep.refobjid = a.attrelid \
                AND dep.refobjsubid = a.attnum \
                AND dep.deptype = 'a' \
                AND a.attidentity = '' \
                AND a.attnotnull \
                AND ad.adbin IS NOT NULL \
                AND pg_catalog.pg_get_expr(ad.adbin, ad.adrelid) LIKE 'nextval(%' \
            LIMIT 1 \
         ) serial_seq ON TRUE \
         WHERE c.relname = $1 \
            AND n.nspname = 'public' \
            AND a.attnum > 0 \
            AND NOT a.attisdropped \
         ORDER BY a.attnum",
        )
        .bind(table)
        .fetch_all(&pool)
        .await
        .map_err(|e| e.to_string())?;

    let columns = column_rows
        .into_iter()
        .map(
            |(name, data_type, not_null, default_expr, identity, serial_type)| PgColumnDdl {
                name,
                data_type,
                not_null,
                default_expr,
                identity,
                serial_type,
            },
        )
        .collect();

    let constraints = sqlx::query_as::<_, (String, String)>(
        "SELECT \
            con.conname, \
            pg_catalog.pg_get_constraintdef(con.oid, true) \
         FROM pg_catalog.pg_constraint con \
         JOIN pg_catalog.pg_class c ON c.oid = con.conrelid \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         WHERE c.relname = $1 \
            AND n.nspname = 'public' \
            AND con.contype IN ('p', 'u', 'c', 'f', 'x') \
         ORDER BY \
            CASE con.contype \
                WHEN 'p' THEN 1 \
                WHEN 'u' THEN 2 \
                WHEN 'f' THEN 3 \
                WHEN 'c' THEN 4 \
                WHEN 'x' THEN 5 \
                ELSE 6 \
            END, \
            con.conname",
    )
    .bind(table)
    .fetch_all(&pool)
    .await
    .map_err(|e| e.to_string())?
    .into_iter()
    .map(|(name, definition)| PgConstraintDdl { name, definition })
    .collect();

    Ok(TableDdl {
        ddl: render_pg_create_table(table, columns, constraints),
        dialect: "postgres".to_string(),
        source: "generated".to_string(),
    })
}


pub(super) async fn fetch_pg_structure(
    pool: &sqlx::PgPool,
    table: &str,
) -> Result<TableStructure, String> {
    // Single query: column info + is_primary + is_foreign_key + is_indexed
    let rows = sqlx::query_as::<_, (String, String, String, String, bool, bool, bool, Option<String>)>(
        "SELECT \
            a.attname, \
            t.typname, \
            pg_catalog.format_type(a.atttypid, a.atttypmod), \
            CASE WHEN a.attnotnull THEN 'NO' ELSE 'YES' END, \
            EXISTS( \
                SELECT 1 FROM pg_catalog.pg_constraint con \
                WHERE con.conrelid = cl.oid \
                    AND con.contype = 'p' \
                    AND a.attnum = ANY(con.conkey) \
            ), \
            EXISTS( \
                SELECT 1 FROM pg_catalog.pg_constraint con \
                WHERE con.conrelid = cl.oid \
                    AND con.contype = 'f' \
                    AND a.attnum = ANY(con.conkey) \
            ), \
            EXISTS( \
                SELECT 1 FROM pg_catalog.pg_index ix \
                WHERE ix.indrelid = cl.oid \
                    AND NOT ix.indisprimary \
                    AND a.attnum = ANY(ix.indkey) \
            ), \
            pg_catalog.pg_get_expr(ad.adbin, ad.adrelid) \
        FROM pg_catalog.pg_attribute a \
        JOIN pg_catalog.pg_class cl ON cl.oid = a.attrelid \
        JOIN pg_catalog.pg_namespace n ON n.oid = cl.relnamespace \
        JOIN pg_catalog.pg_type t ON t.oid = a.atttypid \
        LEFT JOIN pg_catalog.pg_attrdef ad \
            ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum \
        WHERE cl.relname = $1 \
            AND n.nspname = 'public' \
            AND a.attnum > 0 \
            AND NOT a.attisdropped \
        ORDER BY a.attnum",
    )
    .bind(table)
    .fetch_all(pool)
    .await
    .map_err(|e| e.to_string())?;

    let columns = rows
        .into_iter()
        .map(
            |(name, typname, format_type, is_nullable, is_primary, is_fk, is_indexed, default_expr)| {
                StructureColumn {
                    name,
                    data_type: normalize_pg_type(&typname),
                    type_params: extract_type_params(&format_type),
                    is_nullable: is_nullable == "YES",
                    is_primary,
                    is_foreign_key: is_fk,
                    is_indexed,
                    default_value: default_expr,
                    mysql: None,
                }
            },
        )
        .collect();

    Ok(TableStructure {
        columns,
        dialect: "postgres".to_string(),
    })
}


/// Drops run first so a rename can reuse a dropped column's name.
pub(super) fn generate_pg_alter(
    table: &str,
    current: &[StructureColumn],
    changes: &StructureChanges,
) -> Result<Vec<String>, String> {
    if changes.reorder.is_some() {
        return Err(
            "Column reordering is not supported for PostgreSQL. Use the DDL tab to recreate the table."
                .to_string(),
        );
    }
    let mut stmts = Vec::new();
    let qt = pg_quote(table);
    let cols = col_map(current);
    let edits = resolve_edits(&cols, changes)?;

    for col_name in &changes.drops {
        stmts.push(format!(
            "ALTER TABLE {} DROP COLUMN {};",
            qt,
            pg_quote(col_name)
        ));
    }

    for (orig, edit) in edits {
        if edit.name != edit.original_name {
            stmts.push(format!(
                "ALTER TABLE {} RENAME COLUMN {} TO {};",
                qt,
                pg_quote(&edit.original_name),
                pg_quote(&edit.name)
            ));
        }

        let col_q = pg_quote(&edit.name);
        let new_type = type_with_params(&edit.data_type, edit.type_params.as_deref());
        let orig_type = type_with_params(&orig.data_type, orig.type_params.as_deref());

        if new_type != orig_type {
            stmts.push(format!(
                "ALTER TABLE {} ALTER COLUMN {} TYPE {};",
                qt, col_q, new_type
            ));
        }

        if edit.nullable != orig.is_nullable {
            stmts.push(format!(
                "ALTER TABLE {} ALTER COLUMN {} {} NOT NULL;",
                qt,
                col_q,
                if edit.nullable { "DROP" } else { "SET" }
            ));
        }

        if edit.default_value != orig.default_value {
            match &edit.default_value {
                Some(val) if !val.is_empty() => stmts.push(format!(
                    "ALTER TABLE {} ALTER COLUMN {} SET DEFAULT {};",
                    qt, col_q, val
                )),
                _ => stmts.push(format!(
                    "ALTER TABLE {} ALTER COLUMN {} DROP DEFAULT;",
                    qt, col_q
                )),
            }
        }
    }

    for add in &changes.adds {
        let full_type = type_with_params(&add.data_type, add.type_params.as_deref());
        stmts.push(format!(
            "ALTER TABLE {} ADD COLUMN {};",
            qt,
            add_column_def(pg_quote(&add.name), full_type, add)
        ));
    }

    Ok(stmts)
}

